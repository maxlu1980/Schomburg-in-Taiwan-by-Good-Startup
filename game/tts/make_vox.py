# Mira's German lines -> neural speech (Supertonic 3 via sherpa-onnx, speaker 3: a young woman's voice) -> trimmed, levelled MP3s
# -> src/koeln/isle/k_vox.js (base64 clips keyed by line id, and the spoken text for each, so dialogue lines match too)
import os as _os, pathlib as _pl
ROOT = _pl.Path(_os.environ.get('SG_ROOT') or _pl.Path(__file__).resolve().parents[2])  # the repository root
SRC = ROOT / 'src' / 'koeln'
import sherpa_onnx as s, numpy as np, wave, json, subprocess, base64, re, os, sys
M = str(ROOT / 'game' / 'tts' / 'model') + '/'; OUT = str(ROOT / 'game' / 'tts' / 'vox') + '/'; os.makedirs(OUT, exist_ok=True)
SID = int(os.environ.get('VOX_SID', '3'))
st = s.OfflineTtsSupertonicModelConfig(duration_predictor=M + 'duration_predictor.onnx', text_encoder=M + 'text_encoder.onnx', vector_estimator=M + 'vector_estimator.onnx', vocoder=M + 'vocoder.onnx', tts_json=M + 'tts.json', unicode_indexer=M + 'unicode_indexer.bin', voice_style=M + 'voice.bin')
mc = s.OfflineTtsModelConfig(); mc.supertonic = st; mc.num_threads = 4; mc.provider = 'cpu'
tts = s.OfflineTts(s.OfflineTtsConfig(model=mc)); SR = tts.sample_rate
L = json.load(open(ROOT / 'game' / 'tts' / 'lines.json', encoding='utf-8'))
# how to say it: abbreviations and numbers spelt as spoken, dashes and ellipses as pauses, brand names as words
SAY = [(r'MG 42', 'M G zweiundvierzig'), (r'\bMP\b', 'M P'), (r'SCHOMBURG', 'Schomburg'), (r'NO AFTERLIFE', 'No Afterlife'), (r'\bDLC\b', 'D L C'), (r'Good-Startup-Stand', 'Good Startup Stand'),
       (r'\s*–\s*', ', '), (r'\s*…\s*', '... '), (r'\?!', '?'), (r'Pssst!', 'Psst!'), (r'Aaaaah!', 'Aaaah!'), (r'Iiih!', 'Iih!')]
def spoken(t):
    for a, b in SAY: t = re.sub(a, b, t)
    return re.sub(r'\s+', ' ', t).strip().replace(' ,', ',')
FAST = set(['goken', 'goken_b', 'ryusui', 'ryusui_b', 'iai', 'iai_b', 'genmu', 'genmu_b', 'seiki', 'seiki_b', 'win', 'miss', 'sp_charge', 'sp_star', 'sp_lance', 'sp_aurora', 'net', 'sq_see', 'dr_see', 'bz_rage'])
def trim(x):
    a = np.abs(x); th = max(1e-3, a.max() * 0.02); idx = np.where(a > th)[0]
    if not len(idx): return x
    i0 = max(0, idx[0] - int(0.03 * SR)); i1 = min(len(x), idx[-1] + int(0.12 * SR)); y = x[i0:i1].copy()
    f = int(0.008 * SR); y[:f] *= np.linspace(0, 1, f); y[-f * 4:] *= np.linspace(1, 0, f * 4); return y
def level(x):
    # speech-active RMS to -18 dBFS, peaks held under -1.5 dBFS (a soft limiter)
    fr = int(0.02 * SR); e = np.array([np.sqrt(np.mean(x[i:i + fr] ** 2)) for i in range(0, len(x) - fr, fr)]); act = e[e > e.max() * 0.1]
    g = 10 ** (-18 / 20) / max(1e-4, np.sqrt(np.mean(act ** 2))); y = x * g; lim = 10 ** (-1.5 / 20)
    return np.tanh(y / lim) * lim if np.abs(y).max() > lim else y
seen = {}; data = {}; texts = {}; total = 0
for k, t in L.items():
    sp = spoken(t)
    if sp in seen: data[k] = data[seen[sp]]; texts[k] = t; continue
    g = s.GenerationConfig(); g.sid = SID; g.speed = 1.12 if k in FAST else 1.04; g.num_steps = 10; g.extra = {'lang': 'de'}
    a = tts.generate(sp, g); x = level(trim(np.array(a.samples, dtype=np.float32)))
    wp = OUT + k + '.wav'
    with wave.open(wp, 'wb') as w: w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR); w.writeframes((np.clip(x, -1, 1) * 32767).astype(np.int16).tobytes())
    mp = OUT + k + '.mp3'; subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', wp, '-ac', '1', '-ar', '24000', '-c:a', 'libmp3lame', '-b:a', '40k', mp], check=True)
    b = open(mp, 'rb').read(); total += len(b); data[k] = base64.b64encode(b).decode(); texts[k] = t; seen[sp] = k
    print('%-10s %5.2fs %6d B  %s' % (k, len(x) / SR, len(b), sp))
js = '  /* ===== ISLE part K6 (Köln): Mira\'s voice — every line she says, spoken in German by a neural voice (Supertonic 3, a young woman\'s\n     voice, generated offline) and kept here as MP3 clips, so she is heard on every device (no speech engine needed); generated by\n     tools/make_vox.py ===== */\n'
js += '  var VOXC = ' + json.dumps(data, separators=(',', ':')) + ';\n'
js += '  var VOXT = ' + json.dumps(texts, ensure_ascii=False, separators=(',', ':')) + ';\n'
js += open(ROOT / 'game' / 'tts' / 'voxplay.js', encoding='utf-8').read()
open(SRC / 'isle' / 'k_vox.js', 'w', encoding='utf-8').write(js)
print('clips', len(data), 'bytes', total, 'js', len(js))
