#!/usr/bin/env python3
"""Validate the German chunks (i18n/de/cNNN.json) against the English (i18n/chunks/cNNN.json) and build src/de.js.
   Checks per string: present, placeholders {x} kept, HTML tag names kept (as a multiset), product tokens {P4}/{M30r} kept, no stray English where the English is a sentence.
   Strings missing from the German keep their English (the page falls back anyway) and are listed. Usage: python3 i18n/assemble.py [--strict]"""
import json, pathlib, re, sys, copy
R = pathlib.Path(__file__).parent; EN = json.load(open(R / 'en.json', encoding='utf-8'))
chunks = sorted((R / 'chunks').glob('c*.json')); DE = {}; missing_files = []; problems = []; count = 0; same = []
PH = re.compile(r'\{[^{}]*\}'); TAG = re.compile(r'<\s*/?\s*([a-zA-Z][a-zA-Z0-9]*)')
for cf in chunks:
    en = json.load(open(cf, encoding='utf-8')); df = R / 'de' / cf.name
    if not df.exists(): missing_files.append(cf.name); continue
    de = json.load(open(df, encoding='utf-8'))
    for k, v in en.items():
        if k not in de: problems.append((cf.name, k, 'missing')); continue
        d = de[k]
        if not isinstance(d, str): problems.append((cf.name, k, 'not a string')); continue
        if sorted(PH.findall(v)) != sorted(PH.findall(d)): problems.append((cf.name, k, 'placeholders %s → %s' % (PH.findall(v), PH.findall(d))))
        if sorted(t.lower() for t in TAG.findall(v)) != sorted(t.lower() for t in TAG.findall(d)): problems.append((cf.name, k, 'tags %s → %s' % (TAG.findall(v), TAG.findall(d))))
        if d == v and len(v) > 24 and re.search(r'\b(the|and|with|of|for|is|are|to)\b', v): same.append((cf.name, k, v[:60]))
        DE[k] = d; count += 1
    for k in de:
        if k not in en: problems.append((cf.name, k, 'unknown key'))
# rebuild the values: a deep copy of the English with the German leaves
def put(v, ptr, path):
    if isinstance(v, str): return DE.get(path + '|' + ptr, v)
    if isinstance(v, list): return [put(x, ptr + '/' + str(i), path) for i, x in enumerate(v)]
    if isinstance(v, dict): return {k: put(x, ptr + '/' + k.replace('~', '~0').replace('/', '~1'), path) for k, x in v.items()}
    return v
out = ['/* ===== Deutsch: generated by i18n/assemble.py from i18n/de/*.json — do not edit by hand ===== */', '(function () { var _n = 0;']
for path, v in EN.items():
    if path.startswith('CMP.'): continue  # the comparison data carries its own en / zh / de since the many-manufacturer edition (cmp/merge.py)
    val = put(v, '', path)
    out.append('try { ' + path + '.de = ' + json.dumps(val, ensure_ascii=False) + '; _n++; } catch (e) {}')
# our own values of the comparison tables (plain strings beside {en, zh} objects): CMP…params[j].ours → oursDe, charts[j].oursLabel → oursLabelDe
OURS = json.load(open(R / 'ours_en.json', encoding='utf-8')); OD = {}
for f in sorted((R / 'de').glob('ours_*.json')): OD.update(json.load(open(f, encoding='utf-8')))
for k, v in OURS.items():
    if k not in OD: problems.append(('ours', k, 'missing')); continue
    if sorted(PH.findall(v)) != sorted(PH.findall(OD[k])): problems.append(('ours', k, 'placeholders'))
    pass  # oursDe now lives in the CMP data itself
for k in OD:
    if k not in OURS: problems.append(('ours', k, 'unknown key'))
out.append('window.DE_DICTS = _n; })();')
(R.parent / 'src' / 'de.js').write_text('\n'.join(out) + '\n', encoding='utf-8')
total = sum(len(json.load(open(c, encoding='utf-8'))) for c in chunks)
print('German strings', count, 'of', total, '(%.1f %%)' % (100.0 * count / total), '· chunks missing:', len(missing_files), ' '.join(missing_files[:40]))
print('problems', len(problems)); [print('  ', p[0], p[1][:70], p[2][:140]) for p in problems[:60]]
print('left in English (sentence-like, identical)', len(same)); [print('  ', p[0], p[1][:60], p[2]) for p in same[:30]]
if '--strict' in sys.argv and (problems or missing_files): sys.exit(1)
